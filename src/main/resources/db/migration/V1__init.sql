
    create table components (
        id bigint generated by default as identity,
        description varchar(255),
        name varchar(100) not null,
        project_id bigint not null,
        primary key (id)
    );

    create table issue_links (
        id bigint generated by default as identity,
        link_type varchar(255) not null check ((link_type in ('DUPLICATE','BLOCKS','RELATES_TO'))),
        source_issue_id bigint not null,
        target_issue_id bigint not null,
        primary key (id),
        constraint uk_issue_link_pair unique (source_issue_id, target_issue_id, link_type)
    );

    create table issue_tags (
        issue_id bigint not null,
        tag_id bigint not null,
        primary key (issue_id, tag_id)
    );

    create table issues (
        id bigint generated by default as identity,
        created_at timestamp(6) not null,
        deadline date,
        description TEXT,
        priority varchar(255) not null check ((priority in ('LOW','MEDIUM','HIGH','CRITICAL'))),
        resolution varchar(255) check ((resolution in ('FIXED','NOT_A_BUG','DUPLICATE','CANNOT_REPRODUCE'))),
        status varchar(255) not null check ((status in ('NEW','PLANNED','IN_PROGRESS','REQUIRES_CLARIFICATION','IN_REVIEW','CLOSED','REOPENED'))),
        steps_to_reproduce TEXT,
        title varchar(255) not null,
        updated_at timestamp(6),
        assignee_id bigint,
        component_id bigint,
        fix_release_id bigint,
        project_id bigint not null,
        release_id bigint,
        reporter_id bigint not null,
        primary key (id)
    );

    create table project_members (
        id bigint generated by default as identity,
        joined_at timestamp(6) not null,
        role varchar(255) not null check ((role in ('TEAM_LEAD','DEVELOPER','TESTER','OBSERVER'))),
        project_id bigint not null,
        user_id bigint not null,
        primary key (id),
        constraint uk_project_member_project_user unique (project_id, user_id)
    );

    create table projects (
        id bigint generated by default as identity,
        created_at timestamp(6) not null,
        description TEXT,
        git_repo_url varchar(255),
        is_active boolean not null,
        name varchar(100) not null unique,
        tracking_active boolean not null,
        updated_at timestamp(6),
        created_by bigint not null,
        primary key (id)
    );

    create table releases (
        id bigint generated by default as identity,
        is_released boolean not null,
        release_date date,
        version_name varchar(50) not null,
        project_id bigint not null,
        primary key (id)
    );

    create table tags (
        id bigint generated by default as identity,
        color varchar(7),
        name varchar(50) not null,
        project_id bigint not null,
        primary key (id)
    );

    create table users (
        id bigint generated by default as identity,
        created_at timestamp(6) not null,
        email varchar(100) not null unique,
        full_name varchar(100) not null,
        updated_at timestamp(6),
        username varchar(50) not null unique,
        primary key (id)
    );

